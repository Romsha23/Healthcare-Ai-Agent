class NumberedCanvas(canvas.Canvas):
    """Two-pass canvas that computes and renders the total page count on every page."""

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self._saved_page_states: list[dict[str, Any]] = []

    def showPage(self) -> None:
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count: int) -> None:
        self.saveState()
        # Footer rule line
        self.setStrokeColor(colors.HexColor("#cbd5e1"))
        self.setLineWidth(0.6)
        self.line(36, 42, letter[0] - 36, 42)

        # Footer text
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))
        self.drawString(
            36,
            30,
            "Confidential Medical Record • Generated by Healthcare AI Assistant • For Clinical Decision Support",
        )
        page_text = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(letter[0] - 36, 30, page_text)
        self.restoreState()


def _format_markdown_inline(text: str) -> str:
    """Safely converts markdown inline formatting (**bold**, *italic*, `code`) into ReportLab XML."""
    # Split text into tokens for bold, italic, code, and plain text
    parts = re.split(r"(\*\*.*?\*\*|\*.*?\*|`.*?`)", text)
    out: list[str] = []
    for p in parts:
        if not p:
            continue
        if p.startswith("**") and p.endswith("**") and len(p) >= 4:
            clean = html.escape(p[2:-2])
            out.append(f"<b>{clean}</b>")
        elif p.startswith("*") and p.endswith("*") and len(p) >= 2:
            clean = html.escape(p[1:-1])
            out.append(f"<i>{clean}</i>")
        elif p.startswith("`") and p.endswith("`") and len(p) >= 2:
            clean = html.escape(p[1:-1])
            out.append(f"<font face='Courier' color='#0f766e'><b>{clean}</b></font>")
        else:
            out.append(html.escape(p))
    return "".join(out)


def generate_clinical_summary_pdf(
    summary_text: str,
    entities: dict[str, Any],
    key_alerts: Optional[list[str]] = None,
    action_items: Optional[list[str]] = None,
    advices: Optional[dict[str, list[str]]] = None,
    doc_title: str = "CLINICAL SUMMARY & PATIENT CARE PLAN",
) -> bytes:
    """Generates a complete, professional, publication-quality medical PDF report.

    Args:
        summary_text: Markdown or plain text clinical summary.
        entities: Extracted patient intelligence (demographics, vitals, labs, medications).
        key_alerts: Optional list of high-priority clinical or safety alerts.
        action_items: Optional list of doctor's action items / recommendations.
        advices: Optional dictionary with categorized patient care advices
                 (diet, medications, warnings, lifestyle).
        doc_title: Primary title for the document header.

    Returns:
        bytes: Raw PDF binary content ready for download or transmission.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=36,
        rightMargin=36,
        topMargin=36,
        bottomMargin=54,
    )

    styles = getSampleStyleSheet()

    # Custom Typography Hierarchy
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#0f766e"),
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#64748b"),
    )
    section_h1 = ParagraphStyle(
        "SectionH1",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=13,
        leading=17,
        textColor=colors.HexColor("#0f766e"),
        spaceBefore=12,
        spaceAfter=6,
    )
    section_h2 = ParagraphStyle(
        "SectionH2",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=10.5,
        leading=14,
        textColor=colors.HexColor("#1e293b"),
        spaceBefore=8,
        spaceAfter=4,
    )
    body_style = ParagraphStyle(
        "BodyDark",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9.5,
        leading=13.5,
        textColor=colors.HexColor("#1e293b"),
        spaceAfter=4,
    )
    bullet_style = ParagraphStyle(
        "BulletDark",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#334155"),
        leftIndent=14,
        firstLineIndent=-10,
        spaceAfter=3,
    )
    alert_style = ParagraphStyle(
        "AlertItem",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=9,
        leading=13,
        textColor=colors.HexColor("#991b1b"),
        spaceAfter=3,
    )
    table_cell = ParagraphStyle(
        "TableCell",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=8.5,
        leading=11.5,
        textColor=colors.HexColor("#1e293b"),
    )
    table_cell_bold = ParagraphStyle(
        "TableCellBold",
        parent=styles["Normal"],
        fontName="Helvetica-Bold",
        fontSize=8.5,
        leading=11.5,
        textColor=colors.HexColor("#0f766e"),
    )

    story: list[Any] = []

    # ── 1. Top Header & Hospital Branding ─────────────────────────────────────
    header_table_data = [
        [
            Paragraph(f"<b>{doc_title}</b>", title_style),
            Paragraph(
                f"<div align='right'><b>DATE:</b> {datetime.now().strftime('%d %b %Y %H:%M')}<br/>"
                f"<b>STATUS:</b> <font color='#0d9488'>AI VERIFIED</font></div>",
                subtitle_style,
            ),
        ],
        [
            Paragraph("Healthcare AI Assistant • Smart Clinical Decision Support Platform", subtitle_style),
            Paragraph("<div align='right'>CONFIDENTIAL MEDICAL SUMMARY</div>", subtitle_style),
        ],
    ]
    t_header = Table(header_table_data, colWidths=[380, 160])
    t_header.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 0),
    ]))
    story.append(t_header)
    story.append(Spacer(1, 4))
    story.append(HRFlowable(width="100%", thickness=2, color=colors.HexColor("#0f766e"), spaceAfter=10))

    # ── 2. Patient Demographics & Encounter Table ─────────────────────────────
    p_id = entities.get("patient_id", "P001")
    p_name = entities.get("patient_name", f"Patient {p_id}")
    age = entities.get("age", "")
    gender = entities.get("gender", "")
    demo = f"{age}yo {gender}".strip() if (age or gender) else "Standard"
    doctor = entities.get("doctor") or "Attending Physician"
    facility = entities.get("facility") or "Hospital Clinical Care Center"
    conditions = entities.get("conditions", [])
    primary_cond = conditions[0] if conditions else entities.get("sample_type", "Clinical Evaluation")

    demo_data = [
        [
            Paragraph("<b>Patient Name:</b>", table_cell_bold),
            Paragraph(str(p_name), table_cell),
            Paragraph("<b>Patient ID:</b>", table_cell_bold),
            Paragraph(f"<font face='Courier'>{p_id}</font>", table_cell),
        ],
        [
            Paragraph("<b>Demographics:</b>", table_cell_bold),
            Paragraph(demo, table_cell),
            Paragraph("<b>Primary Indication:</b>", table_cell_bold),
            Paragraph(str(primary_cond), table_cell),
        ],
        [
            Paragraph("<b>Attending Doctor:</b>", table_cell_bold),
            Paragraph(str(doctor), table_cell),
            Paragraph("<b>Facility / Clinic:</b>", table_cell_bold),
            Paragraph(str(facility), table_cell),
        ],
    ]

    t_demo = Table(demo_data, colWidths=[105, 165, 110, 160])
    t_demo.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f8fafc")),
        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#cbd5e1")),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#e2e8f0")),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]))
    story.append(t_demo)
    story.append(Spacer(1, 10))

    # ── 3. Vitals & Lab Measurements Strip (If present) ───────────────────────
    vitals = entities.get("vitals", {})
    egfr = entities.get("egfr")
    cr = entities.get("creatinine")
    vital_items: list[tuple[str, str]] = []

    if "BP" in vitals:
        vital_items.append(("Blood Pressure", vitals["BP"]))
    if "HR" in vitals:
        vital_items.append(("Heart Rate", vitals["HR"]))
    if "SpO2" in vitals:
        vital_items.append(("Oxygen Saturation", vitals["SpO2"]))
    if egfr is not None:
        vital_items.append(("Kidney eGFR", f"{egfr} mL/min"))
    if cr is not None:
        vital_items.append(("Creatinine", f"{cr} mg/dL"))

    if vital_items:
        v_cells = []
        for lab_label, lab_val in vital_items[:5]:
            v_cells.append(Paragraph(f"<b>{lab_label}:</b> {lab_val}", table_cell))
        # Pad up to 5 cols if needed
        while len(v_cells) < 5:
            v_cells.append(Paragraph("", table_cell))
        
        t_vitals = Table([v_cells], colWidths=[108] * 5)
        t_vitals.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f0fdfa")),
            ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#2dd4bf")),
            ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#99f6e4")),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("LEFTPADDING", (0, 0), (-1, -1), 6),
            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
            ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ]))
        story.append(t_vitals)
        story.append(Spacer(1, 10))

    # ── 4. Key Alerts Box (If any alerts exist) ───────────────────────────────
    if key_alerts:
        alert_rows = []
        for alert_txt in key_alerts:
            alert_rows.append([Paragraph(f"• <b>CRITICAL ALERT:</b> {_format_markdown_inline(alert_txt)}", alert_style)])
        
        t_alert = Table(alert_rows, colWidths=[540])
        t_alert.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#fef2f2")),
            ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#ef4444")),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("LEFTPADDING", (0, 0), (-1, -1), 10),
            ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ]))
        story.append(t_alert)
        story.append(Spacer(1, 10))
    elif entities.get("lab_results") and all(r.get("result") in ["NEGATIVE", "NON-REACTIVE", "NORMAL", "NOT DETECTED"] for r in entities["lab_results"]):
        clear_row = [[Paragraph("• <b>SURGERY CLEARANCE CONFIRMED:</b> All tested blood infection markers are Clear / Negative. Patient is approved for procedure.", ParagraphStyle("ClearAlert", parent=styles["Normal"], fontName="Helvetica-Bold", fontSize=9, textColor=colors.HexColor("#15803d")))]]
        t_clear = Table(clear_row, colWidths=[540])
        t_clear.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#f0fdf4")),
            ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#22c55e")),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ("LEFTPADDING", (0, 0), (-1, -1), 10),
            ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ]))
        story.append(t_clear)
        story.append(Spacer(1, 10))

    # ── 5. Main Clinical Summary Content ──────────────────────────────────────
    story.append(Paragraph("Clinical Evaluation & Summary", section_h1))
    story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#cbd5e1"), spaceAfter=8))

    # Parse summary_text line by line
    clean_lines = summary_text.strip().split("\n")
    skip_advice_in_body = False

    for line in clean_lines:
        line_s = line.strip()
        if not line_s:
            story.append(Spacer(1, 3))
            continue

        # If the summary already has the advice heading, stop parsing main body
        # (we will render the structured advice section beautifully right below)
        if "PRACTICAL HEALTH & DAILY CARE ADVICE" in line_s or "PRACTICAL ADVICES FOR PATIENT" in line_s:
            skip_advice_in_body = True
            break

        if line_s.startswith("### "):
            header_text = line_s[4:].strip()
            story.append(Paragraph(_format_markdown_inline(header_text), section_h1))
        elif line_s.startswith("#### "):
            header_text = line_s[5:].strip()
            story.append(Paragraph(_format_markdown_inline(header_text), section_h2))
        elif line_s.startswith("- ") or line_s.startswith("* "):
            bullet_text = line_s[2:].strip()
            story.append(Paragraph(f"• {_format_markdown_inline(bullet_text)}", bullet_style))
        elif re.match(r"^\d+\.\s+", line_s):
            m = re.match(r"^(\d+\.)\s+(.*)$", line_s)
            if m:
                num_tag = m.group(1)
                text_part = m.group(2)
                story.append(Paragraph(f"<b>{num_tag}</b> {_format_markdown_inline(text_part)}", bullet_style))
        else:
            story.append(Paragraph(_format_markdown_inline(line_s), body_style))

    # ── 6. Doctor's Next Steps (Action Items) ─────────────────────────────────
    if action_items:
        story.append(Spacer(1, 6))
        story.append(Paragraph("Doctor's Next Steps & Action Plan", section_h1))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#cbd5e1"), spaceAfter=6))
        
        for i, item in enumerate(action_items, 1):
            story.append(Paragraph(f"<b>{i}.</b> {_format_markdown_inline(item)}", bullet_style))

    # ── 7. Practical Patient Health & Care Advice Section ─────────────────────
    if advices:
        story.append(Spacer(1, 8))
        story.append(KeepTogether([
            Paragraph("Practical Health & Care Advice for Patient & Family", section_h1),
            HRFlowable(width="100%", thickness=1.5, color=colors.HexColor("#0f766e"), spaceAfter=8),
        ]))

        # Helper to render an advice category table card
        def _render_advice_card(title: str, items: list[str], bg_color: str, border_color: str) -> Table:
            card_rows: list[list[Any]] = [
                [Paragraph(f"<b>{title}</b>", ParagraphStyle(
                    "AdviceCardTitle",
                    parent=styles["Normal"],
                    fontName="Helvetica-Bold",
                    fontSize=9.5,
                    textColor=colors.HexColor("#0f766e"),
                ))]
            ]
            for it in items:
                card_rows.append([Paragraph(f"• {_format_markdown_inline(it)}", bullet_style)])
            t_card = Table(card_rows, colWidths=[540])
            t_card.setStyle(TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(bg_color)),
                ("BOX", (0, 0), (-1, -1), 1, colors.HexColor(border_color)),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
            ]))
            return t_card

        if advices.get("diet"):
            story.append(_render_advice_card("Diet & Nutrition Recommendations", advices["diet"], "#f8fafc", "#94a3b8"))
            story.append(Spacer(1, 6))

        if advices.get("medications"):
            story.append(_render_advice_card("Medication Safety & Pill Routine", advices["medications"], "#f8fafc", "#94a3b8"))
            story.append(Spacer(1, 6))

        if advices.get("warnings"):
            story.append(_render_advice_card("Urgent Warning Signs (When to Seek Emergency Help)", advices["warnings"], "#fef2f2", "#fca5a5"))
            story.append(Spacer(1, 6))

        if advices.get("lifestyle"):
            story.append(_render_advice_card("Daily Home Monitoring & Clinic Follow-Up", advices["lifestyle"], "#f8fafc", "#94a3b8"))
            story.append(Spacer(1, 6))

    # Build the document with our two-pass NumberedCanvas
    doc.build(story, canvasmaker=NumberedCanvas)
    return buffer.getvalue()
